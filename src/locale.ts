export function translator(options: ImageEditorOptions) {
  const locale = options.locale ?? 'en',
    language = locale.split('-')[0],
    index = Math.max(0, ['en', 'cs', 'sk', 'pl'].indexOf(language));
  return (key: string) =>
    options.translations?.[locale]?.[`image_editor.${key}`] ??
    options.translations?.[language]?.[`image_editor.${key}`] ??
    labels[key]?.[index] ??
    labels[key]?.[0] ??
    key;
}
